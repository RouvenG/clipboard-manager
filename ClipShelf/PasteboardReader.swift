import AppKit
import CryptoKit

/// A value copy of one pasteboard state, decoupled from SwiftData.
struct ClipSnapshot: Equatable {
    var kind: ClipKind
    var text: String?
    var rtfData: Data?
    var htmlData: Data?
    var imageData: Data?
    var fileURLStrings: [String] = []
    var codeLanguage: String?

    var contentHash: String {
        var hasher = SHA256()
        hasher.update(data: Data(kind.rawValue.utf8))
        switch kind {
        case .image:
            hasher.update(data: imageData ?? Data())
        case .file:
            hasher.update(data: Data(fileURLStrings.joined(separator: "\n").utf8))
        case .text, .richText, .link:
            hasher.update(data: Data((text ?? "").utf8))
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

enum PasteboardReader {
    /// Types that apps set to say "do not record this" (nspasteboard.org conventions plus legacy vendor types).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Marker ClipShelf adds to its own writes so the monitor does not re-record them.
    static let ownWriteType = NSPasteboard.PasteboardType("io.github.rouveng.clipshelf.own")

    static let maxImageBytes = 25 * 1024 * 1024

    static func shouldIgnore(types: [NSPasteboard.PasteboardType]) -> Bool {
        types.contains { ignoredTypes.contains($0.rawValue) }
    }

    static func snapshot(from pasteboard: NSPasteboard) -> ClipSnapshot? {
        let types = pasteboard.types ?? []
        guard !types.isEmpty, !shouldIgnore(types: types), !types.contains(ownWriteType) else { return nil }

        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipSnapshot(
                kind: .file,
                text: urls.map(\.path).joined(separator: "\n"),
                fileURLStrings: urls.map(\.absoluteString)
            )
        }

        let string = pasteboard.string(forType: .string)

        if string == nil, let image = imageData(from: pasteboard, types: types) {
            return ClipSnapshot(kind: .image, imageData: image)
        }

        guard let string, !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }

        if let link = LinkDetector.link(in: string) {
            return ClipSnapshot(kind: .link, text: link)
        }

        let rtf = pasteboard.data(forType: .rtf)
        let html = pasteboard.data(forType: .html)
        return ClipSnapshot(
            kind: rtf != nil || html != nil ? .richText : .text,
            text: string,
            rtfData: rtf,
            htmlData: html,
            codeLanguage: CodeDetector.language(of: string)
        )
    }

    private static func imageData(from pasteboard: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> Data? {
        if types.contains(.png), let png = pasteboard.data(forType: .png), png.count <= maxImageBytes {
            return png
        }
        if types.contains(.tiff), let tiff = pasteboard.data(forType: .tiff), tiff.count <= maxImageBytes * 4,
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]), png.count <= maxImageBytes {
            return png
        }
        return nil
    }
}

enum LinkDetector {
    private static let schemes: Set<String> = ["http", "https", "mailto", "ftp", "ssh", "file"]

    /// Returns the trimmed string when the whole clip is a single URL.
    static func link(in string: String) -> String? {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
              schemes.contains(scheme) else { return nil }
        if scheme == "http" || scheme == "https" {
            guard let host = url.host, host.contains(".") || host == "localhost" else { return nil }
        }
        return trimmed
    }
}
